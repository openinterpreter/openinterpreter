CREATE TABLE thread_goal_creation_receipts (
    thread_id TEXT NOT NULL,
    creation_id TEXT NOT NULL,
    request_digest TEXT NOT NULL,
    previous_goal_id TEXT NOT NULL,
    previous_objective TEXT NOT NULL,
    previous_status TEXT NOT NULL CHECK(previous_status IN (
        'active',
        'paused',
        'blocked',
        'usage_limited',
        'budget_limited',
        'complete'
    )),
    previous_token_budget INTEGER,
    previous_tokens_used INTEGER NOT NULL,
    previous_time_used_seconds INTEGER NOT NULL,
    previous_mission_revision INTEGER NOT NULL,
    previous_lifecycle_revision INTEGER NOT NULL,
    previous_created_at_ms INTEGER NOT NULL,
    previous_updated_at_ms INTEGER NOT NULL,
    goal_id TEXT NOT NULL,
    objective TEXT NOT NULL,
    status TEXT NOT NULL CHECK(status IN (
        'active',
        'paused',
        'blocked',
        'usage_limited',
        'budget_limited',
        'complete'
    )),
    token_budget INTEGER,
    tokens_used INTEGER NOT NULL,
    time_used_seconds INTEGER NOT NULL,
    mission_revision INTEGER NOT NULL,
    lifecycle_revision INTEGER NOT NULL,
    created_at_ms INTEGER NOT NULL,
    updated_at_ms INTEGER NOT NULL,
    document_path TEXT NOT NULL,
    document_sha256 TEXT NOT NULL,
    document_byte_length INTEGER NOT NULL,
    document_updated_at_ms INTEGER NOT NULL,
    PRIMARY KEY(thread_id, creation_id)
);
